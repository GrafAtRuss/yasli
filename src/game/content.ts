export function stationsFor(length: Length): Station[] {
  return STATIONS.filter((station) => length === "evening" || station.short);
}

export function quizFor(station: Station, role: Role): Quiz | null {
  if (station.together) return null;
  const quiz = role === "child" ? station.child : station.adult;
  return quiz ?? null;
}

